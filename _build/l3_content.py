def rcard(n, t, d, m, go):
    return f'<button class="rcard" data-go="{go}"><div class="n">{n}</div><b>{t}</b><span>{TX(d)}</span><em>{m}</em></button>'


def QCARD(*paras):
    return '<div class="card qstem">' + ''.join(f'<p>{TX(p)}</p>' for p in paras) + '</div>'


def SUMX(sid, title, points, fx, demo, kick=None):
    """An interim summary that uses the whole slide: the points on the right, and on the left the formula they rest on,
    and then, on the following clicks, a worked line piece by piece."""
    ol = '<ol class="steps sumup">' + ''.join(ST(i + 1, '<span>' + TX(p) + '</span>', 'li') for i, p in enumerate(points)) + '</ol>'
    n = len(points) + 1
    card = ST(n, '<b class="ct">' + TX('הנוסחה שעליה זה נשען') + '</b>' + EQ(fx, key=True) + '<p class="sp">' + _atoms(demo, lambda j: SUB(n)(j + 1))[0] + '</p>', cls='card fxs')
    S(sid, title, title, f'<div class="row eq2 top"><div>{ol}</div><div>{card}</div></div>', kick=kick or f'חלק {CUR[0]} · מה למדנו')


def CARD(n, title, *paras, extra=''):
    """A card that opens on step n and then fills sentence by sentence; a formula under it comes last."""
    if not n:
        return f'<div class="card"><b class="ct">{TX(title)}</b>' + ''.join(f'<p class="lg">{TX(p)}</p>' for p in paras) + extra + '</div>'
    st, k, inner = SUB(n), 0, f'<b class="ct">{TX(title)}</b>'
    for p in paras:
        h, c = _atoms(p, lambda j, k=k: st(k + j)); inner += f'<p class="lg">{h}</p>'; k += c
    if extra: inner += f'<div class="st" data-n="{st(k)}">{extra}</div>'
    return ST(n, inner, cls='card')


