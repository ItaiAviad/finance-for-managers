COV = {'y': ('✓', 'נלמד'), 'p': ('◐', 'חלקית'), 'n': ('✗', 'במפגש 4')}


def MAPCOV(rows):
    """The assignment map with a coverage column: (question, topic, mark, note, [(label, target)]). Rows reveal one by one."""
    h = '<tr>' + ''.join(f'<th>{TX(x)}</th>' for x in ('במטלה', 'הנושא', 'במפגש 3', 'איפה במצגות (לחצו כדי לעבור)')) + '</tr>'
    b = ''
    for i, (q, t, m, note, refs) in enumerate(rows):
        tr = f'<tr class="st" data-n="{(i + 1) * 10}">' if i else '<tr>'
        sym, lab = COV[m]
        b += (tr + f'<td>{TX(q)}</td><td>{TX(t)}</td><td class="cov {m}"><b>{sym} {TX(lab)}</b>' + (f'<small>{TX(note)}</small>' if note else '') + '</td><td>'
              + ' · '.join(GO(l, g) for l, g in refs) + '</td></tr>')
    return f'<table class="tbl2 mmn mcov">{h}{b}</table>'


