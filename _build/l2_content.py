def BOX(sid, title, cards, legend_of, band=None, kick=None):
    """A formula box: one card per formula, each with its words and a demo taken from the exercise just solved."""
    html = '<div class="col">' + ''.join(
        (f'<div class="card fm st" data-n="{i * 10}">' if i else '<div class="card fm">') + f'<b>{h}</b><p>{TX(w)}</p><div class="eq" dir="ltr">'
        + '&emsp;&emsp;'.join(M(e) for e in eqs) + f'</div><div class="demo">{TX(d)}</div></div>' for i, (h, w, eqs, d) in enumerate(cards)) + '</div>'
    html += legend(legend_of)
    if band: html += BAND(band[0], band[1], len(cards))
    S(sid, title, title, html, kick=kick or f'חלק {CUR[0]} · ארגז הנוסחאות')


